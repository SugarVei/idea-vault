"""Rebuild the tiny inlined previews from the finished small-card artwork."""
import base64
import io
import json
from pathlib import Path

from PIL import Image

root = Path(__file__).resolve().parents[1]
samples = {}
for poster in sorted((root / "assets" / "compact").glob("*.webp")):
    with Image.open(poster) as source:
        if source.width != source.height:
            raise ValueError(f"Compact poster must be square: {poster.name}")
        small = source.convert("RGB").resize((40, 40), Image.Resampling.LANCZOS)
    buffer = io.BytesIO()
    small.save(buffer, format="WEBP", quality=48, method=6)
    samples[poster.stem] = base64.b64encode(buffer.getvalue()).decode("ascii")

output = "// Generated by scripts/build-compact-samples.py from assets/compact/.\n"
output += "export const compactSamples = " + json.dumps(samples, indent=2) + ";\n"
(root / "compact-samples.js").write_bytes(output.encode("utf-8"))
